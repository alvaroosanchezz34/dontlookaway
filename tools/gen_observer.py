def skin(n=1024):
    """Ash-dark skin: mottled, grey veins raised under the surface, fine
    wrinkles, a wet sheen that varies (roughness low where it glistens)."""
    mottle = tex.spectral(n, 2.4, 201)
    fine = tex.spectral(n, 0.9, 202)
    veins_raw = tex.band(n, 5, 14, 203) - 0.5
    veins = np.exp(-(veins_raw / 0.012) ** 2) * tex.smoothstep(0.4, 0.7, tex.spectral(n, 2.0, 204))
    capill = np.exp(-((tex.band(n, 20, 45, 205) - 0.5) / 0.008) ** 2) * 0.5
    wrinkles = tex.band(n, 60, 140, 206)
    wet = tex.smoothstep(0.45, 0.85, tex.spectral(n, 2.2, 207))
    pale = tex.smoothstep(0.7, 0.9, tex.spectral(n, 2.6, 208))
    base = tex.rgb(26, 25, 27) * np.ones((n, n, 1))
    col = base * (0.75 + 0.35 * mottle + 0.1 * fine)[..., None]
    col = tex.mix(col, tex.rgb(64, 66, 74), np.clip(veins * 0.8 + capill * 0.4, 0, 1))
    col = tex.mix(col, tex.rgb(70, 66, 64), pale * 0.35)
    h = fine * 0.3 + wrinkles * 0.25 + veins * 0.6 + capill * 0.2 + mottle * 0.2
    rough = 0.55 - wet * 0.35 + 0.1 * wrinkles
    os.makedirs(OUT, exist_ok=True)
    Image.fromarray((np.clip(col, 0, 1) * 255).astype(np.uint8), "RGB").save(os.path.join(OUT, "observer_skin_color.png"), optimize=True)
    nm = tex.normal_from_height(h, 3.0)
    Image.fromarray((np.clip(nm, 0, 1) * 255).astype(np.uint8), "RGB").save(os.path.join(OUT, "observer_skin_normal.png"), optimize=True)
    Image.fromarray((np.clip(rough, 0, 1) * 255).astype(np.uint8), "L").save(os.path.join(OUT, "observer_skin_roughness.png"), optimize=True)
    print("wrote observer skin")


def main():
    os.makedirs(OUT, exist_ok=True)
    meta = []
    for name, build in SEGMENTS.items():
        mesh = build()
        tris = mesh.write_obj(os.path.join(OUT, name + ".obj"))
        lo, hi = mesh.bbox()
        size = hi - lo
        center = (hi + lo) / 2
        meta.append((name, size, center))
        print("%-11s %5d tris  size %.2f %.2f %.2f" % (name, tris, size[0], size[1], size[2]))
    skin()
    with open(META, "w") as fh:
        fh.write("--[[\n\tObserverMeshMeta (generated by tools/gen_observer.py - do not edit)\n")
        fh.write("\tBounding box of every Observer mesh in its rig part's local space: the\n")
        fh.write("\tgame sizes each MeshPart to `size` and places it at `offset` from the part.\n]]\n\n")
        fh.write("return {\n")
        for name, size, center in meta:
            fh.write("\t%s = { size = Vector3.new(%.4f, %.4f, %.4f), offset = Vector3.new(%.4f, %.4f, %.4f) },\n" % (name, size[0], size[1], size[2], center[0], center[1], center[2]))
        fh.write("}\n")
    print("wrote", os.path.relpath(META, ROOT))


if __name__ == "__main__":
    main()
