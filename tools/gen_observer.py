"""
Mesh + skin generator for THE OBSERVER.

Builds one organic mesh per rig segment (same names and sizes as the parts in
src/shared/ObserverRig.luau), each in that part's local space (Y up, front -Z),
plus a seamless PBR skin (colour / normal / roughness).

Outputs:
    assets/observer/<Segment>.obj
    assets/observer/observer_skin_{color,normal,roughness}.png
    src/shared/Config/ObserverMeshMeta.luau   (bounding box of every mesh, so the
                                                game places and sizes them exactly)

Usage:
    python3 tools/gen_observer.py
"""

